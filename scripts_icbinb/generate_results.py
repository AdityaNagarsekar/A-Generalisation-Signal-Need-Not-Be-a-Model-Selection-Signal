#!/usr/bin/env python3
"""Regenerate artifacts/results/summaries/RESULTS.md from whatever is complete on disk.
Run at the end of each section."""
from __future__ import annotations
import glob, sys
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent
sys.path[:0] = [str(ROOT), str(ROOT / "src")]
import pandas as pd, numpy as np
from icbinb.analysis import per_condition, SELECTORS

POOL = ROOT / "artifacts/results" / "phase1a_pool" / "candidates"
OUT  = ROOT / "artifacts/results" / "summaries" / "RESULTS.md"
REPS = {"caco2_random":20,"caco2_scaffold":20,"lipo_random":30,"lipo_scaffold":30,
        "cond7":20,"amylase":20,"hydro":30}
ORDER = ["caco2_random","caco2_scaffold","lipo_random","lipo_scaffold","cond7","amylase","hydro"]
SHIFTY = {"caco2_random":"IID control (low-n)","caco2_scaffold":"structural OOD (low-n; val also OOD)",
          "lipo_random":"IID control","lipo_scaffold":"structural OOD (val also OOD)",
          "cond7":"**ID-like val -> OOD test** (the hypothesis)","amylase":"position shift",
          "hydro":"**fitness extrapolation** (+4.6 train-sigma)"}

def sig(p):
    return "" if not np.isfinite(p) else ("***" if p<0.001 else "**" if p<0.01 else "*" if p<0.05 else "")

def main():
    L = ["# RESULTS — ICBINB-BIO 2026 (Phase 1A)", "",
         "*Auto-generated by `scripts_icbinb/generate_results.py`; regenerated at the end of "
         "each section. Protocol locked and hashed before any of this was inspected.*", "",
         "**Reading the tables.** Lower test MSE is better. `vs val` is the paired median "
         "difference in deployed OOD loss ($\\Delta L$, plan §1 RQ3); **negative means the "
         "selector beats validation**. `p` is a paired Wilcoxon over outer runs. "
         "Significance marks are *uncorrected*; the pre-registered confirmatory family is "
         "`fg_legacy` vs `val` over {cond7, caco2_scaffold, amylase, hydro} with Holm.", ""]
    done = []
    for cond in ORDER:
        fs = sorted(glob.glob(f"{POOL}/{cond}/*.parquet"))
        if not fs: continue
        df = pd.concat([pd.read_parquet(f) for f in fs], ignore_index=True)
        nrun = df.outer_run.nunique(); complete = nrun >= REPS[cond]
        if complete: done.append(cond)
        r = per_condition(df)
        L += [f"## {cond} — {SHIFTY[cond]}", "",
              f"{nrun}/{REPS[cond]} outer runs {'**(done)**' if complete else '(partial)'} · "
              f"{len(df)} models · {int((df.status_train!='ok').sum())} training failures · "
              f"{int((df.status_proxy!='ok').sum())} proxy failures", "",
              "| selector | median test MSE | vs val ($\\Delta L$) | wins | p |",
              "|---|---:|---:|---:|---:|"]
        for s in SELECTORS:
            med = r["deploy"][s][0]
            if s == "val":
                L.append(f"| `val` (baseline) | {med:.4f} | — | — | — |"); continue
            d, m, p, w = r["contrast"][s]
            L.append(f"| `{s}` | {med:.4f} | {d:+.4f} | {w}/{nrun} | {p:.3f}{sig(p)} |")
        L += ["", "**Rank transfer** — Spearman $\\rho$(signal, test), median over runs:", "",
              "| signal | $\\rho$ | $\\rho$ partial (given val) |", "|---|---:|---:|"]
        for c, lab in [("val_mse_std","val"),("fg_legacy","fg_legacy"),("fg_penult","fg_penult"),
                       ("hess_top","hess_top"),("train_mse_std","train_mse"),
                       ("n_params","n_params (confound)"),("dead_relu_frac","dead_relu_frac (confound)")]:
            pr = r["per_run"].get(f"rhopart_{c}")
            prs = f"{pr.median():+.3f}" if pr is not None else "—"
            L.append(f"| {lab} | {r['per_run'][f'rho_{c}'].median():+.3f} | {prs} |")
        # degeneracy audit of what each selector actually deployed
        deg=[]
        for sel,col in [("val","val_mse_std"),("fg_legacy","fg_legacy"),
                        ("fg_penult","fg_penult"),("hess_top","hess_top")]:
            ds,pv=[],[]
            for _,g in df[df.status_train=="ok"].groupby("outer_run"):
                gg=g.dropna(subset=[col])
                if len(gg)==0: continue
                i=gg[col].idxmin(); ds.append(gg.loc[i,"dead_relu_frac"]); pv.append(gg.loc[i,"pred_std_test"])
            if ds: deg.append((sel,float(np.median(ds)),float(np.median(pv))))
        if deg:
            L += ["", "**Degeneracy audit of the deployed model** — a selector that keeps "
                  "picking a dead / constant-output network is exploiting a degenerate "
                  "solution, not identifying a good one:", "",
                  "| selector | dead_relu_frac of pick | pred_std_test of pick | |",
                  "|---|---:|---:|---|"]
            for sel,d_,p_ in deg:
                flag = " **DEGENERATE**" if (d_>0.9 or p_<0.01) else ""
                L.append(f"| `{sel}` | {d_:.3f} | {p_:.4f} |{flag} |")
        L += ["", f"Selected-model OOD percentile: val {r['per_run'].pct_val.median():.0f}% · "
                  f"fg_legacy {r['per_run'].pct_fg.median():.0f}% "
                  f"(lower = better; 50% = no better than a random candidate)", ""]
    L += ["---", "", "## Interpretation caveats (pre-registered)", "",
          "* **Caco2 has a ~91-example validation set.** With 48 candidates, val-MSE is a "
          "noisy estimator, so a proxy beating `val` on Caco2 may reflect *validation "
          "estimator noise* rather than proxy quality. This is exactly the pre-registered "
          "§8.2 concern, and is why the Caco2 5-fold-CV control exists. Do not read the "
          "Caco2 rows as evidence about geometry until that control is run.",
          "* **IID control conditions are not the hypothesis.** `caco2_random` and "
          "`lipo_random` exist to show what happens when validation is *reliable*. A proxy "
          "win there is interesting but is not evidence for the shift hypothesis.",
          "* **`lipo_scaffold` / `caco2_scaffold` are not ID-val -> OOD-test** (verified: "
          "0.0% train/val scaffold overlap). Only `cond7` and `hydro` test the central "
          "hypothesis.",
          "* **Uncorrected p-values.** Per-condition marks are exploratory; the "
          "confirmatory claim uses Holm across the pre-registered family only.",
          "* **`hess_top` is a control, not a competing proposal** — it answers whether "
          "activation energy is standing in for true curvature.", "",
          "## Status", "",
          f"Conditions complete: {', '.join(f'`{c}`' for c in done) if done else 'none'}.",
          f"Remaining: {', '.join(f'`{c}`' for c in ORDER if c not in done)}.", "",
          "This file covers **Phase 1A only** (ranking a fixed shared pool). The other "
          "sections live alongside it and are regenerated by their own scripts:", "",
          "* `RESULTS_phase1b.md` — sequential HPO, 9 methods "
          "(`scripts_icbinb/analyze_phase1b.py`)",
          "* `RESULTS_ablations.md` — fixed-architecture and val-free ablations "
          "(`scripts_icbinb/analyze_ablations.py`)", "",
          "No confirmatory claim is made until every pre-registered condition, phase and "
          "ablation is complete."]
    OUT.parent.mkdir(parents=True, exist_ok=True); OUT.write_text("\n".join(L) + "\n")
    print(f"wrote {OUT}  ({len(done)} complete conditions)")

if __name__ == "__main__":
    main()
