def runs_1b(cond, clean=True):
    """Phase 1B has no shared pool: each (method, outer_run) IS its own 48-trial pool,
    generated by that method's own search. Returns one DataFrame per (method, run) —
    9 methods x 10 runs = 90 pools per condition — so `random(E)` means 'a random pick
    among the trials this search actually produced'."""
    out = []
    for m in SEARCHES:
        for f in sorted(glob.glob(f"{SEQ}/{m}/{cond}/*.parquet")):
            d = pd.read_parquet(f)
            d = d[(d.status_train == "ok") & d.val_mse_std.notna()]
            if clean:
                d = d[(d.pred_std_test >= 1e-6) & (d.dead_relu_frac <= DEAD)]
            if len(d) >= 5:
                out.append(d)
    return out


def save(fig, name):
    """Vector PDF for LaTeX, plus a genuinely high-resolution PNG for viewing.

    The PNG is rendered by matplotlib at 300 dpi rather than by rasterising the PDF
    afterwards -- converting a 72 dpi PDF render and upscaling produces a blurry
    image no matter how good the vector source is."""
    fig.savefig(f"{FIG}/{name}.pdf")
    fig.savefig(f"{FIG}/{name}.png", dpi=300)
    plt.close(fig)
    print(f"{name}.pdf + .png")


