def fig1():
    n = len(ORDER)
    ncol = 4 if n > 2 else n
    nrow = int(np.ceil((n + (1 if n > 2 else 0)) / ncol))
    fig, axes = plt.subplots(nrow, ncol, figsize=(2.0*ncol, 2.4*nrow), squeeze=False)
    axes = axes.ravel()
    for ax, cond in zip(axes, ORDER):
        R = runs(POOL, cond)
        rnd = np.array([pick(k, "__rand") for k in R])
        names, meds, los, his = [], [], [], []
        for nm, sp in SELS:
            v = np.array([_np_sel(k, sp) for k in R])
            rel = 100.0 * (v - rnd) / rnd           # % vs random selection
            lo, hi = boot_ci(rel)
            names.append(nm); meds.append(np.median(rel)); los.append(lo); his.append(hi)
        y = np.arange(len(names))[::-1]
        for i, nm in enumerate(names):
            is_val = nm == "val"
