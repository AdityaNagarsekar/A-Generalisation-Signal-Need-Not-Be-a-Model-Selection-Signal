def fig3():
    """Rank-rank transfer. Validation and test MSE live on very different scales
    under extrapolation (on `hydro`, test loss is ~20x validation loss), so a
    shared-scale identity line is meaningless there. Selection is rank-based
    throughout this study, so the rank-rank view is both the scale-free choice and
    the one that matches the decision actually being made: the diagonal is perfect
    rank transfer, and spread away from it is exactly what makes validation useless."""
    show = [c for c in ["lipo_random", "lipo_scaffold", "cond7", "hydro"] if c in ORDER] or ORDER
    fig, axes = plt.subplots(1, len(show), figsize=(2.0*len(show), 2.5), squeeze=False)
    axes = axes.ravel()
    for ax, cond in zip(axes, show):
        R = runs(POOL, cond)
        rho = float(np.median([spearmanr(k.val_mse_std, k.test_mse_std).statistic for k in R]))
        xs, ys = [], []
        for k in R:                      # rank WITHIN each outer run, then pool
            n = len(k)
            xs.append(rankdata(k.val_mse_std) / n)
            ys.append(rankdata(k.test_mse_std) / n)
        x, y = np.concatenate(xs), np.concatenate(ys)
        ax.scatter(x, y, s=4, alpha=0.22, color=INK, linewidths=0)
        ax.plot([0, 1], [0, 1], ls="--", lw=1.0, color=ACCENT, zorder=3)
        ax.set_xlim(0, 1); ax.set_ylim(0, 1)
        ax.set_xticks([0, .5, 1]); ax.set_yticks([0, .5, 1])
        ax.set_aspect("equal")
        ax.set_title(f"{NICE.get(cond, NICE_DEFAULT(cond)).splitlines()[0]}\n" + r"median $\rho$ = " + f"{rho:+.2f}", pad=3)
        ax.set_xlabel("validation rank")
        ax.tick_params(length=2)
    axes[0].set_ylabel("test rank")
    fig.suptitle("Does the validation ranking survive deployment?   "
                 "(dashed = perfect transfer; best candidate at rank 0)",
                 fontsize=8.5, y=1.02)
    fig.tight_layout()
    save(fig, "fig3_val_on_the_line")


