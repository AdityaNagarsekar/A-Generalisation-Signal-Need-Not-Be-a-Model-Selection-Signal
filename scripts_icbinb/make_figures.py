def _deploy(g, sig):
    ok = g[(g.status_train == "ok") & g.val_mse_std.notna()]
    if not len(ok):
        return np.nan
    if sig == "__train":
        return float(ok.loc[ok.train_mse_std.idxmin(), "test_mse_std"])
    if sig is None:
        return float(ok.loc[ok.val_mse_std.idxmin(), "test_mse_std"])
    o = ok[ok[sig].notna()]
    if not len(o):
        return np.nan
    return float(o.iloc[int(np.argmin(rankdata(o.val_mse_std) + rankdata(o[sig])))].test_mse_std)


def fig2():
    """THE central claim: the deploy rule that helps under scaffold mismatch hurts
    under fitness extrapolation, and curvature does the reverse.

    Every stored trial carries val, train and all three signals, so any deploy rule
    can be applied post hoc to ANY search trajectory. Pooling over all nine searches
    (n=90 paired per condition) isolates the deploy rule from the search strategy.
    Identical panel layout across the two conditions so the reversal reads as a
    mirror image, per the ICBINB Entropic-winner's Fig. 2 device."""
    from scipy.stats import wilcoxon
    fig, axes = plt.subplots(1, 2, figsize=(7.2, 2.9), sharex=False)
    for ax, cond, title in zip(axes, ["cond7", "hydro"],
                               ["Cond7  (scaffold mismatch)", "Hydro  (fitness extrapolation)"]):
        dfs = {m: [pd.read_parquet(f) for f in sorted(glob.glob(f"{SEQ}/{m}/{cond}/*.parquet"))]
               for m in SEARCHES}
        base = np.concatenate([[_deploy(g, None) for g in dfs[m]] for m in SEARCHES])
        rows = []
        for name, sig in DEPLOY:
            v = np.concatenate([[_deploy(g, sig) for g in dfs[m]] for m in SEARCHES])
            d = v - base
            ok = np.isfinite(d)
            d = d[ok]
            pct = 100.0 * d / np.median(base)
            p = float(wilcoxon(d).pvalue) if np.any(d != 0) else 1.0
            rows.append((name, float(np.median(pct)), int((d < 0).sum()), int((d > 0).sum()), p,
                         boot_ci(pct)))
        y = np.arange(len(rows))[::-1]
        for i, (nm, med, b, w, p, (lo, hi)) in enumerate(rows):
            # decide fill by the WIN/LOSS direction, not the median: rank-sum ties
            # with `val` on many runs, so the median % can sit at exactly 0 while the
            # paired test is decisive (e.g. cond7 val+legacy: median 0.00, 43/25, p<.001)
            helps = b > w
            ax.plot([lo, hi], [y[i], y[i]], color=INK, lw=1.4, solid_capstyle="round", zorder=2)
            ax.plot(med, y[i], "o" if helps else "s", ms=7,
                    mfc=INK if helps else "white", mec=INK, mew=1.4, zorder=3)
            star = "***" if p < 0.001 else ("**" if p < 0.01 else ("*" if p < 0.05 else ""))
            ax.text(1.02, y[i], f"{b}/{w}{star}", transform=ax.get_yaxis_transform(),
                    va="center", fontsize=7, color=INK)
        ax.axvline(0, color=ACCENT, lw=1.1, ls="--", zorder=1)
        ax.set_yticks(y); ax.set_yticklabels([r[0] for r in rows])
        ax.set_title(title, pad=4)
        ax.set_xlabel("deployed loss vs `val` alone (%)")
        ax.tick_params(length=2)
        ax.set_ylim(-0.7, len(rows) - 0.3)
    axes[0].plot([], [], "o", ms=6, mfc=INK, mec=INK, label="helps")
    axes[0].plot([], [], "s", ms=6, mfc="white", mec=INK, mew=1.4, label="hurts")
    axes[0].legend(frameon=False, loc="lower right", handletextpad=0.3,
                   borderpad=0.1, fontsize=7)
    fig.suptitle("The same augmentation helps under one biological shift and hurts under the other\n"
                 "pooled over all 9 search strategies (n=90 paired); counts are better/worse, "
                 "* p<.05  ** p<.01  *** p<.001",
                 fontsize=9, y=1.10)
    fig.tight_layout()
    save(fig, "fig2_signflip")


