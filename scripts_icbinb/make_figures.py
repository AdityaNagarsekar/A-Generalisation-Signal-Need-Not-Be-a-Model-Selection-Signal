def _pcorr(d, x, y, ctrl):
    """Spearman partial correlation: rank-residualise both variables on the controls."""
    R = np.column_stack([np.ones(len(d))] + [rankdata(d[c]) for c in ctrl])
    def res(v):
        v = rankdata(v); b, *_ = np.linalg.lstsq(R, v, rcond=None); return v - R @ b
    return spearmanr(res(d[x]), res(d[y])).statistic


